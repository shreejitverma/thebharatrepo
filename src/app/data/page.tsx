import fs from 'node:fs';
import path from 'node:path';
import type { Metadata } from 'next';
import Link from 'next/link';
import { DATA_DIR, DATA_FILES, DATA_LICENSE, DATA_LICENSE_URL, readManifest, type DataFile } from '@/lib/content/open-data';
import { REPO_URL } from '@/lib/content/site-url';

export const metadata: Metadata = {
  title: 'Open data',
  description: 'Download every entity, dating, source and correction in The Bharat Repo as JSON and CSV, with a schema and SHA-256 checksums, under CC BY-SA 4.0.',
};

function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} bytes`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(0)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

const dateFormat = new Intl.DateTimeFormat('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });

export default function DataPage() {
  // The bundle is generated by `npm run data:export` before `next build`; a missing or malformed manifest fails the build.
  const manifest = readManifest();
  const size = (name: string) => formatBytes(fs.statSync(path.join(DATA_DIR, name)).size);
  const files = (Object.keys(DATA_FILES) as DataFile[]).map((name) => ({ name, ...DATA_FILES[name], size: size(name), sha256: manifest.sha256[name] }));
  const { counts } = manifest;
  const totals: [number, string][] = [
    [counts.entities, 'entities'],
    [counts.datings, 'datings'],
    [counts.sources, 'sources'],
    [counts.articles, 'articles'],
    [counts.corrections, 'corrections'],
  ];

  return (
    <div className="main-content data-page">
      <div className="prose-wrap">
        <p className="eyebrow">Open data</p>
        <h1>Download the archive</h1>
        <p className="lede" style={{ marginTop: 0 }}>
          Everything the site is built from, as JSON and CSV under {DATA_LICENSE}. The files are regenerated from the validated content on every build and
          checked by re-importing them through the same validators.
        </p>
      </div>

      <dl className="data-counts" aria-label="What the export contains">
        {totals.map(([n, label]) => (
          <div key={label}>
            <dt>{label}</dt>
            <dd>{n.toLocaleString('en-IN')}</dd>
          </div>
        ))}
      </dl>
      <p className="muted data-asof">
        {manifest.contentCommitDate ? (
          <>
            Content as of its last change on <time dateTime={manifest.contentCommitDate}>{dateFormat.format(new Date(manifest.contentCommitDate))}</time>.
          </>
        ) : (
          manifest.contentCommitDateNote
        )}{' '}
        Schema version {manifest.schemaVersion}.
      </p>

      <ul className="data-files">
        {files.map((f) => (
          <li key={f.name} className="data-file">
            <h2>{f.label}</h2>
            <p className="data-file__meta">
              <span>{f.format}</span>
              <span>{f.size}</span>
            </p>
            <p>{f.description}</p>
            <p className="data-file__sum">
              <span className="muted">SHA-256</span> <code>{f.sha256}</code>
            </p>
            <a className="btn" href={`/data/${f.name}`} download>
              Download {f.name}
            </a>
          </li>
        ))}
        <li className="data-file">
          <h2>Manifest</h2>
          <p className="data-file__meta">
            <span>JSON</span>
            <span>{size('manifest.json')}</span>
          </p>
          <p>The schema version, licence, record counts, content date and the SHA-256 checksum of every other file.</p>
          <a className="btn" href="/data/manifest.json" download>
            Download manifest.json
          </a>
        </li>
      </ul>

      <div className="prose-wrap">
        <h2>Reading the data</h2>
        <ul>
          <li>
            Years use astronomical numbering, so 1 BCE is year 0 and 2 BCE is year -1. Deep-time dates, written in the archive as ka or Ma, are stored as calendar years
            the same way.
          </li>
          <li>
            Every dating carries its method and its <Link href="/methodology">evidence grade</Link>. Traditional reckonings have a traditional method and grade D; they
            record what a tradition holds and are not dated history.
          </li>
          <li>
            An entity can have several datings. In datings.csv, <code>primary</code> marks the one that stands for the entity across the site: scholarship before
            tradition, then the strongest grade. The <code>primaryDate</code> column in entities.csv is that dating as the site writes it.
          </li>
          <li>
            The review status of each entry is exported with it. A <code>draft</code> has machine-verified identifiers and is awaiting human editorial review.
          </li>
          <li>
            To check a download, compare the output of <code>shasum -a 256 archive.json</code> with its entry in manifest.json.
          </li>
        </ul>

        <h2>Licence and attribution</h2>
        <p>
          The data is licensed under <a href={DATA_LICENSE_URL}>Creative Commons Attribution-ShareAlike 4.0 International</a>. When you reuse it, credit The Bharat
          Repo, link to the licence, say what you changed, and share your version under the same licence. Images are referenced by their Wikimedia Commons file name
          and keep their own licences.
        </p>
        <p>
          Found a mistake? <a href={`${REPO_URL}/issues/new?template=correction.yml`}>Request a correction</a>, or see the <Link href="/corrections">corrections log</Link>.
        </p>
      </div>
    </div>
  );
}
